export function getYoutubeChannelsForSubject(subjectName: string): string[] {
  if (!subjectName) return [];
  const normalized = subjectName.toLowerCase().trim();
  
  if (YOUTUBE_CHANNELS_MAP[normalized]) {
    return YOUTUBE_CHANNELS_MAP[normalized];
  }
  
  // Fuzzy match
  for (const [key, channels] of Object.entries(YOUTUBE_CHANNELS_MAP)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return channels;
    }
  }
  
  // Generic fallback based on keywords
  if (normalized.includes('matematik') || normalized.includes('geometri')) {
    return YOUTUBE_CHANNELS_MAP['matematik'];
  }
  if (normalized.includes('fizik')) {
    return YOUTUBE_CHANNELS_MAP['fizik'];
  }
  if (normalized.includes('kimya')) {
    return YOUTUBE_CHANNELS_MAP['kimya'];
  }
  if (normalized.includes('biyoloji')) {
    return YOUTUBE_CHANNELS_MAP['biyoloji'];
  }
  if (normalized.includes('türkçe') || normalized.includes('paragraf')) {
    return YOUTUBE_CHANNELS_MAP['türkçe'];
  }
  if (normalized.includes('edebiyat')) {
    return YOUTUBE_CHANNELS_MAP['edebiyat'];
  }
  if (normalized.includes('tarih')) {
    return YOUTUBE_CHANNELS_MAP['tarih'];
  }
  if (normalized.includes('coğrafya')) {
    return YOUTUBE_CHANNELS_MAP['coğrafya'];
  }
  if (normalized.includes('felsefe')) {
    return YOUTUBE_CHANNELS_MAP['felsefe'];
  }
  if (normalized.includes('din')) {
    return YOUTUBE_CHANNELS_MAP['din kültürü'];
  }

  return ['Rehber Matematik', 'Benim Hocam', 'Hocalara Geldik', 'Tonguç Akademi'];
}

